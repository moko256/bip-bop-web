/**
 * Regenerate src/lib/styles/pico-theme-colors.ts from the Pico Sass entry.
 *
 *   node scripts/generate-pico-theme-colors.mjs
 */
import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { transform } from 'lightningcss';
import { compile } from 'sass-embedded';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const entry = path.join(root, 'src/lib/styles/pico.scss');
const outFile = path.join(root, 'src/lib/styles/pico-theme-colors.ts');
const extractModule = path.join(root, 'src/lib/styles/extract-pico-theme-colors.ts');

const css = compile(entry, {
	style: 'compressed',
	loadPaths: [path.join(root, 'node_modules')],
	quietDeps: true
}).css;

const { code } = transform({
	filename: 'pico.css',
	code: Buffer.from(css),
	minify: true
});

const { extractPicoThemeColors } = await import(pathToFileURL(extractModule).href);
const colors = extractPicoThemeColors(code.toString());

const source = `/** Generated by scripts/generate-pico-theme-colors.mjs — do not edit. */
export const picoThemeColors = {
	light: '${colors.light}',
	dark: '${colors.dark}'
} as const;
`;

await writeFile(outFile, source);
console.log(`Wrote ${path.relative(root, outFile)} (${colors.light}, ${colors.dark})`);
