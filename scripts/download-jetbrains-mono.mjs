/**
 * Download a JetBrains Mono subset for BIP_BOP_FONT_TEXT.
 *
 * Manual only. Not part of `dev`, `build`, or `prepare`.
 *   node --experimental-strip-types scripts/download-jetbrains-mono.mjs
 *
 * A browser user agent is required: without one, the CSS API returns truetype.
 */
import { mkdir, readdir, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { BIP_BOP_FONT_FAMILY, BIP_BOP_FONT_TEXT } from '../src/lib/bip-bop/renderer.ts';

const USER_AGENT =
	'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outDir = path.join(root, 'src/lib/fonts');
const stylesheetName = 'jetbrains-mono.css';

const FONT_URL = /url\(\s*(['"]?)([^'")]+)\1\s*\)(?:\s*format\(\s*(['"]?)([a-z0-9-]+)\3\s*\))?/gi;

/**
 * `https://fonts.googleapis.com/css?family=JetBrains+Mono&text=Hello`
 * @param {string} family
 * @param {string} text
 * @returns {string}
 */
function googleFontsStylesheetUrl(family, text) {
	const familyParam = family.trim().replaceAll(/\s+/g, '+');
	return `https://fonts.googleapis.com/css?family=${familyParam}&text=${encodeURIComponent(text)}`;
}

/**
 * @param {string} format
 * @returns {string}
 */
function extensionForFormat(format) {
	switch (format) {
		case 'woff2':
			return 'woff2';
		case 'woff':
			return 'woff';
		case 'truetype':
			return 'ttf';
		case 'opentype':
			return 'otf';
		case 'embedded-opentype':
			return 'eot';
		default:
			return 'bin';
	}
}

/**
 * @param {string} css
 * @returns {{ url: string, format: string }[]}
 */
function fontSources(css) {
	return [...css.matchAll(FONT_URL)].flatMap((match) => {
		const url = match[2];
		if (url === undefined) return [];
		return [{ url, format: (match[4] ?? 'woff2').toLowerCase() }];
	});
}

/**
 * @param {string} url
 * @returns {Promise<Buffer>}
 */
async function fetchBytes(url) {
	const response = await fetch(url, { headers: { 'User-Agent': USER_AGENT } });
	if (!response.ok) {
		throw new Error(`${response.status} ${response.statusText} for ${url}`);
	}
	return Buffer.from(await response.arrayBuffer());
}

/**
 * @param {string} source
 * @param {string} filepath
 * @returns {Promise<string>}
 */
async function formatStylesheet(source, filepath) {
	const prettier = await import('prettier');
	const config = await prettier.resolveConfig(filepath);
	return prettier.format(source, { ...config, filepath });
}

async function downloadFont() {
	const cssUrl = googleFontsStylesheetUrl(BIP_BOP_FONT_FAMILY, BIP_BOP_FONT_TEXT);
	const cssResponse = await fetch(cssUrl, { headers: { 'User-Agent': USER_AGENT } });
	if (!cssResponse.ok) {
		throw new Error(`${cssResponse.status} ${cssResponse.statusText} for ${cssUrl}`);
	}
	const remoteCss = await cssResponse.text();
	const sources = fontSources(remoteCss);
	if (sources.length === 0) throw new Error(`No font url in the stylesheet from ${cssUrl}`);

	await mkdir(outDir, { recursive: true });

	/** @type {Map<string, string>} */
	const localByUrl = new Map();
	for (const source of sources) {
		if (localByUrl.has(source.url)) continue;
		const bytes = await fetchBytes(source.url);
		if (source.format === 'woff2' && bytes.subarray(0, 4).toString('ascii') !== 'wOF2') {
			throw new Error(`Expected a woff2 payload from ${source.url}`);
		}
		const filename = `jetbrains-mono-${localByUrl.size}.${extensionForFormat(source.format)}`;
		await writeFile(path.join(outDir, filename), bytes);
		localByUrl.set(source.url, filename);
	}

	let css = remoteCss;
	const urls = [...localByUrl.keys()].sort((left, right) => right.length - left.length);
	for (const url of urls) {
		const filename = localByUrl.get(url);
		if (filename === undefined) throw new Error(`Missing local file for ${url}`);
		css = css.replaceAll(url, `./${filename}`);
	}

	const stylesheetPath = path.join(outDir, stylesheetName);
	const generated = [
		'/* Generated by scripts/download-jetbrains-mono.mjs. Do not edit by hand. */',
		css.trim(),
		''
	].join('\n');
	await writeFile(stylesheetPath, await formatStylesheet(generated, stylesheetPath));

	const keep = new Set(localByUrl.values());
	for (const name of await readdir(outDir)) {
		if (keep.has(name) || !/^jetbrains-mono-\d+\.[a-z0-9]+$/.test(name)) continue;
		await rm(path.join(outDir, name));
	}

	console.log(cssUrl);
	console.log(path.relative(root, stylesheetPath));
	for (const filename of localByUrl.values()) console.log(path.join('src/lib/fonts', filename));
}

const isDirectRun =
	process.argv[1] !== undefined &&
	import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href;

if (isDirectRun) {
	await downloadFont();
}
