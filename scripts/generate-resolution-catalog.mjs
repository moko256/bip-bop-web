/**
 * Regenerate src/lib/output/resolution-catalog.ts from landscape sizes.
 *
 *   node scripts/generate-resolution-catalog.mjs
 */
import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outFile = path.join(root, 'src/lib/output/resolution-catalog.ts');

/** Landscape sizes from Wikipedia's computer-graphics resolution table. */
const resolutionSizes = [
	[3840, 2160],
	[3200, 1800],
	[2560, 1440],
	[2048, 1152],
	[1920, 1080],
	[1600, 900],
	[1440, 1080],
	[1280, 720],
	[3200, 2048],
	[2048, 1280],
	[2560, 1600],
	[1920, 1200],
	[1680, 1050],
	[1600, 1024],
	[1440, 900],
	[1280, 800],
	[1280, 768],
	[1920, 1280],
	[1440, 960],
	[2560, 2048],
	[2560, 1920],
	[2048, 1536],
	[1920, 1440],
	[1600, 1200],
	[1400, 1050],
	[1280, 1024],
	[1024, 768],
	[800, 600],
	[640, 480],
	[320, 240],
	[3840, 1600],
	[3440, 1440],
	[2560, 1080]
];

const SIXTEEN_BY_NINE = 16 / 9;

function gcd(a, b) {
	let x = a;
	let y = b;
	while (y !== 0) {
		const next = x % y;
		x = y;
		y = next;
	}
	return x;
}

function aspectRatioLabel(width, height) {
	const g = gcd(width, height);
	return `${width / g}:${height / g}`;
}

function aspectRatioValue(width, height) {
	const g = gcd(width, height);
	return [width / g, height / g];
}

function groupSortKey(width, height) {
	const ratio = width / height;
	if (ratio > SIXTEEN_BY_NINE) {
		return 1_000_000 - Math.round(ratio * 10_000);
	}
	return -Math.round(ratio * 10_000);
}

function formatFraction([numerator, denominator]) {
	return `${numerator} / ${denominator}`;
}

function formatNumber(n) {
	return String(n).replaceAll(/(\d)(?=(\d{3})+(?!\d))/g, '$1_');
}

function catalogEntry(width, height) {
	const value = `${width}x${height}`;
	const pixels = width * height;
	const aspectRatio = aspectRatioLabel(width, height);
	const fraction = aspectRatioValue(width, height);
	return {
		value,
		width,
		height,
		pixels,
		pixelLabel: `${width}×${height}`,
		aspectRatio,
		aspectRatioFraction: fraction,
		groupSortKey: groupSortKey(width, height)
	};
}

const entries = resolutionSizes.map(([width, height]) => catalogEntry(width, height));

const byGroup = new Map();
for (const entry of entries) {
	const group = byGroup.get(entry.aspectRatio) ?? {
		id: entry.aspectRatio,
		label: entry.aspectRatio,
		sortKey: entry.groupSortKey,
		options: []
	};
	group.options.push({ value: entry.value, label: entry.pixelLabel, pixels: entry.pixels });
	byGroup.set(entry.aspectRatio, group);
}

const resolutionGroups = [...byGroup.values()]
	.sort((a, b) => a.sortKey - b.sortKey || a.label.localeCompare(b.label))
	.map((group) => ({
		id: group.id,
		label: group.label,
		options: group.options
			.sort((a, b) => b.pixels - a.pixels)
			.map(({ value, label }) => ({ value, label }))
	}));

const resolutionCatalog = resolutionGroups.flatMap((group) =>
	group.options.map((option) => {
		const entry = entries.find((item) => item.value === option.value);
		if (!entry) throw new Error(`Missing catalog entry for ${option.value}`);
		return entry;
	})
);

function indent(text, spaces) {
	const pad = ' '.repeat(spaces);
	return text
		.split('\n')
		.map((line) => (line.length > 0 ? pad + line : line))
		.join('\n');
}

function renderCatalogEntry(entry) {
	return `{
${indent(
	[
		`value: '${entry.value}',`,
		`width: ${entry.width},`,
		`height: ${entry.height},`,
		`pixels: ${formatNumber(entry.pixels)},`,
		`pixelLabel: '${entry.pixelLabel}',`,
		`aspectRatio: '${entry.aspectRatio}',`,
		`aspectRatioValue: ${formatFraction(entry.aspectRatioFraction)}`
	].join('\n'),
	2
)}
}`;
}

function renderGroup(group) {
	const options = group.options
		.map(
			(option) => `{
${indent([`value: '${option.value}',`, `label: '${option.label}'`].join('\n'), 3)}
}`
		)
		.join(',\n');

	return `{
${indent(
	[
		`id: '${group.id}',`,
		`label: '${group.label}',`,
		`options: [`,
		indent(options, 2),
		`] as const`
	].join('\n'),
	1
)}
}`;
}

const source = `// Generated by scripts/generate-resolution-catalog.mjs — do not edit by hand.
export type ResolutionGroup = {
	id: string;
	label: string;
	options: readonly { value: Resolution; label: string }[];
};

export const resolutionGroups = [
${resolutionGroups.map(renderGroup).join(',\n')}
] as const satisfies readonly ResolutionGroup[];

export const resolutionCatalog = [
${resolutionCatalog.map(renderCatalogEntry).join(',\n')}
] as const;

export type Resolution = (typeof resolutionCatalog)[number]['value'];

export const defaultResolution = '1920x1080' satisfies Resolution;

/** Flat list of resolutions in grouped-select order. */
export const resolutions = resolutionGroups.flatMap(
	(group): ResolutionGroup['options'] => group.options
);
`;

await writeFile(outFile, source, 'utf8');
console.log(`Wrote ${path.relative(root, outFile)}`);
